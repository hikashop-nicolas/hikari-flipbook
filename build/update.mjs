// Writes the update file Joomla asks for when it checks whether a site is behind.
//
// The update server is this repository: the XML is served raw from the default
// branch and the packages come from the release the tag built. Nothing has to be
// hosted anywhere, and there is no server to keep alive for as long as the
// extension is installed anywhere.
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { root, version } from "./lib.mjs";

export const REPO = "hikashop-nicolas/hikari-flipbook";
export const BRANCH = "main";
export const UPDATE_PATH = "updates/pkg_hikariflipbook.xml";

/** Where the manifest points Joomla. Raw, so it is the file and not a web page. */
export const UPDATE_URL = `https://raw.githubusercontent.com/${REPO}/${BRANCH}/${UPDATE_PATH}`;

/** The release asset a tag produces, which is what a site downloads. */
export const downloadUrl = (v) =>
  `https://github.com/${REPO}/releases/download/v${v}/pkg_hikariflipbook-${v}.zip`;

export async function writeUpdateXml(v) {
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build/update.mjs from package.json. Do not edit. -->
<updates>
	<update>
		<name>Hikari Flipbook</name>
		<description>Shows a PDF, an EPUB, a Kindle book, a comic archive or a folder of pages as a book with turning pages.</description>
		<element>pkg_hikariflipbook</element>
		<type>package</type>
		<!-- Without this Joomla assumes "administrator", and the update then matches
		     no installed extension at all: a package is installed against the site.
		     The check finds an update, records it, and never offers it to anyone. -->
		<client>site</client>
		<version>${v}</version>
		<infourl title="Hikari Flipbook">https://github.com/${REPO}</infourl>
		<downloads>
			<downloadurl type="full" format="zip">${downloadUrl(v)}</downloadurl>
		</downloads>
		<tags>
			<tag>stable</tag>
		</tags>
		<maintainer>Hikari Software</maintainer>
		<maintainerurl>https://github.com/${REPO}</maintainerurl>
		<targetplatform name="joomla" version="[456]\\.[0-9]+"/>
		<php_minimum>8.1</php_minimum>
	</update>
</updates>
`;

  await mkdir(join(root, "updates"), { recursive: true });
  await writeFile(join(root, UPDATE_PATH), xml, "utf8");

  return xml;
}

// Run directly as well as being imported by the checks.
if (import.meta.url === `file://${process.argv[1]}`) {
  const v = await version();
  await writeUpdateXml(v);
  console.log(`update: ${UPDATE_PATH} now offers ${v}`);
}
