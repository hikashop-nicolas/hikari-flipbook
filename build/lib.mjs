// Shared build helpers. What the two builds have in common lives here, so a change
// to the shared core cannot reach one package and miss the other.
import archiver from "archiver";
import { createWriteStream } from "node:fs";
import { cp, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

export const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export async function version() {
  const pkg = JSON.parse(await readFile(join(root, "package.json"), "utf8"));
  return pkg.version;
}

/**
 * Copies the platform-free core into a package, adding the host's own guard.
 *
 * The core carries no guard of its own: it is the one body of code both hosts
 * share, and each host spells "refuse to be loaded directly" differently. The
 * guard goes in after the namespace, since PHP will not accept a statement
 * before one.
 */
export async function installCore(target, guard) {
  const lib = join(target, "lib");
  await mkdir(join(lib, "core"), { recursive: true });
  await mkdir(join(lib, "platform"), { recursive: true });

  const order = [];

  for (const [from, into] of [
    [join(root, "src/platform"), join(lib, "platform")],
    [join(root, "src/core"), join(lib, "core")],
  ]) {
    for (const name of (await readdir(from)).filter((n) => n.endsWith(".php")).sort()) {
      const source = await readFile(join(from, name), "utf8");
      await writeFile(join(into, name), addGuard(source, guard), "utf8");
      order.push((into === join(lib, "core") ? "core/" : "platform/") + name);
    }
  }

  // Explicit requires rather than an autoloader: the two hosts register class
  // loaders differently, and this file has to work identically under both.
  const requires = sortForRequire(order)
    .map((f) => `require_once __DIR__ . '/${f}';`)
    .join("\n");

  await writeFile(
    join(lib, "bootstrap.php"),
    `<?php\n/**\n * @package     Hikari.Flipbook\n * @copyright   Copyright (C) 2026 Hikari Software. All rights reserved.\n * @license     GNU General Public License version 3 or later\n *\n * Generated by build/lib.mjs. Do not edit.\n */\n\n${guard}\n\n${requires}\n`,
    "utf8",
  );
}

/** Interfaces and exceptions before the classes that use them. */
function sortForRequire(files) {
  const weight = (f) =>
    f.endsWith("Platform.php") && f.startsWith("platform/") ? 0 : f.includes("Exception") ? 1 : 2;
  return [...files].sort((a, b) => weight(a) - weight(b) || a.localeCompare(b));
}

export function addGuard(source, guard) {
  if (source.includes(guard.split("\n")[0].slice(0, 24))) return source;

  const ns = source.match(/^namespace [^;]+;$/m);
  if (ns) {
    return source.replace(ns[0], `${ns[0]}\n\n${guard}`);
  }
  return source.replace(/^<\?php$/m, `<?php\n\n${guard}`);
}

/** Applies the host guard to every PHP file in a built package. */
export async function guardAll(target, guard) {
  for (const file of await walk(target)) {
    if (!file.endsWith(".php")) continue;
    const body = await readFile(file, "utf8");
    const guarded = addGuard(body, guard);
    if (guarded !== body) await writeFile(file, guarded, "utf8");
  }
}

async function walk(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(path)));
    else out.push(path);
  }
  return out;
}

export async function installMedia(target) {
  await cp(join(root, "dist/media"), join(target, "media"), { recursive: true });
}

export async function zip(folder, name, outFile) {
  await rm(outFile, { force: true });
  const stream = createWriteStream(outFile);
  const archive = archiver("zip", { zlib: { level: 9 } });

  const done = new Promise((resolve, reject) => {
    stream.on("close", resolve);
    archive.on("error", reject);
  });

  archive.pipe(stream);
  archive.directory(folder, name);
  await archive.finalize();
  await done;

  return archive.pointer();
}
